//! Regenerate the terrain of real save games from their seed and settings and compare it with
//! the heights the game stored. Uses the git-ignored `save-game/` and `game-data/` folders;
//! skipped when either is missing.

use banished_formats::game::terrain_generator;
use banished_formats::pkg::{Archive, Package};
use banished_formats::save::Save;
use banished_game::terrain::{CellType, Generator, HeightGrid, SizeRecord};
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn archive() -> Option<Archive> {
    let dir = root().join("game-data/original/WinData");
    let mut a = Archive::default();
    for name in ["data1.pkg", "patch1.pkg", "patch0.pkg", "data0.pkg"] {
        a.add(Package::parse(std::fs::read(dir.join(name)).ok()?).ok()?);
    }
    Some(a)
}

/// Returns the fraction of heights that match. Panics if the save cannot be read.
fn check_save(name: &str) -> Option<f64> {
    let path = root().join("save-game").join(name);
    let (Ok(bytes), Some(archive)) = (std::fs::read(&path), archive()) else {
        eprintln!("{name}: save or game data missing; skipping");
        return None;
    };
    let save = Save::parse(&bytes).unwrap();
    let header = save.loop_header().unwrap();
    let stored = save.map_heights().unwrap();
    let profile = terrain_generator(&archive.read_ref(&header.terrain).unwrap()).unwrap();
    let wire = profile.sizes[header.size_index as usize];
    eprintln!(
        "{name}: seed {} {} size {}",
        header.seed, profile.name, header.size_index
    );

    let mut g = Generator::new(SizeRecord::from_wire(wire), header.seed);
    g.run(|_, _| {});
    let ours = g.heights();
    assert_eq!(ours.len(), stored.heights.len(), "{name}: grid size");
    let w = stored.width;
    let diffs: Vec<usize> = (0..ours.len())
        .filter(|&i| ours[i] != stored.heights[i])
        .collect();
    if std::env::var("DUMP_HEIGHTS").is_ok() {
        let out = root()
            .join("game-data/derived")
            .join(format!("{name}.heights"));
        let mut b = Vec::new();
        for (a, c) in ours.iter().zip(&stored.heights) {
            b.extend_from_slice(&a.to_le_bytes());
            b.extend_from_slice(&c.to_le_bytes());
        }
        std::fs::write(&out, b).unwrap();
    }
    let matched = 1.0 - diffs.len() as f64 / ours.len() as f64;
    if let Some(&i) = diffs.first() {
        let edge = diffs
            .iter()
            .filter(|&&i| i % w == w - 1 || i / w == w - 1)
            .count();
        eprintln!(
            "{name}: {} of {} heights differ ({edge} on the last row/column); first at ({}, {}): ours {} stored {}",
            diffs.len(),
            ours.len(),
            i % w,
            i / w,
            ours[i],
            stored.heights[i]
        );
    } else {
        eprintln!("{name}: all {} heights match", ours.len());
    }
    Some(matched)
}

/// A 2022 save from the current game build. The few differing cells are in-game terrain edits
/// (flattened plateaus at constant heights near the town); everything else is bit-exact.
#[test]
fn allportez() {
    if let Some(m) = check_save("allportez.sav") {
        assert!(m > 0.995, "only {:.4} of heights match", m);
    }
}

/// Seed-290 saves come from a 2015 build whose generator differed slightly (differences across
/// the whole map, symmetric, growing towards the edges). Kept as a report, not an assertion.
#[test]
#[ignore = "generated by an older game build"]
fn starter_save() {
    check_save("starter-save.sav");
}

#[test]
#[ignore = "generated by an older game build"]
fn save2() {
    check_save("Save2.sav");
}

/// Natural cell types (`FUN_1400a3790` over the saved heights) against the saved gameplay map.
/// Cells the player changed (types 0, 3, 4, 5) and cells under objects (bridge and dock
/// footprints stamp their own types) are skipped. The remaining ~0.05% differences sit where
/// buildings reshaped the ground; types are only recomputed when a footprint is cleared.
#[test]
fn allportez_cell_types() {
    let path = root().join("save-game/allportez.sav");
    let Ok(bytes) = std::fs::read(&path) else {
        eprintln!("allportez.sav missing; skipping");
        return;
    };
    let save = Save::parse(&bytes).unwrap();
    let stored = save.map_heights().unwrap();
    let map = save.map_cells().unwrap();
    let grid = HeightGrid {
        width: stored.width,
        heights: &stored.heights,
    };
    let natural = [2u8, 6, 7, 8, 10];
    let (mut compared, mut matched) = (0usize, 0usize);
    let mut confusion = std::collections::BTreeMap::new();
    for (i, cell) in map.cells.iter().enumerate() {
        let saved = cell.cell_type();
        if !natural.contains(&saved) || cell.objects[0] || cell.objects[1] {
            continue;
        }
        compared += 1;
        let ours = grid.natural_cell_type(map.size, i);
        if ours == CellType(saved) {
            matched += 1;
        } else {
            *confusion.entry((saved, ours.0)).or_insert(0usize) += 1;
        }
    }
    let rate = matched as f64 / compared as f64;
    eprintln!(
        "allportez: {matched} of {compared} natural cells match ({:.3}%); (saved, ours) mismatches: {confusion:?}",
        rate * 100.0
    );
    assert!(rate > 0.999, "natural cell types diverge from the save");
}
