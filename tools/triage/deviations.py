"""Collect every known difference from the original into one ledger.

Scans the Rust sources for comments that mark a deviation from the original behaviour or a
piece that is not ported yet, and writes docs/DEVIATIONS.md grouped by crate and file.
Comment blocks are taken whole (consecutive `//` lines around the marker).

Markers (case-insensitive): "deviation", "not ported", "unported", "not traced",
"stands in for", and "instead of"/"rather than" in a comment that names the original.

Usage:
  python3 tools/triage/deviations.py            # rewrite docs/DEVIATIONS.md
  python3 tools/triage/deviations.py --check    # exit 1 if the ledger is stale
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'docs', 'DEVIATIONS.md')
DEPARTS = r'deviation|stands in for|original\b.*\b(instead|rather than)|(instead|rather than)\b.*\boriginal'
MARKER = re.compile(DEPARTS + r'|not ported|unported|not traced', re.I)
KIND = [
    ('Deviation', re.compile(DEPARTS, re.I)),
    ('Not ported', re.compile(r'not ported|unported', re.I)),
    ('Not traced', re.compile(r'not traced', re.I)),
]


def comment_blocks(lines):
    """Yield (first line number, text) for runs of `//` comment lines."""
    start, buf = None, []
    for i, line in enumerate(lines, 1):
        s = line.strip()
        if s.startswith('//'):
            if start is None:
                start = i
            text = s.lstrip('/!').strip()
            # "Original: `FUN_...`" lines only cite the source (the doc-comment style in
            # AGENTS.md); the word "original" in them is not a statement about a difference.
            if not text.startswith('Original:'):
                buf.append(text)
        else:
            if buf:
                yield start, ' '.join(b for b in buf if b)
            start, buf = None, []
    if buf:
        yield start, ' '.join(b for b in buf if b)


def collect():
    entries = []
    for top in ('crates', 'apps'):
        for dirpath, dirs, files in os.walk(os.path.join(ROOT, top)):
            dirs[:] = [d for d in dirs if d not in ('target', 'tests')]
            for fn in sorted(files):
                if not fn.endswith('.rs'):
                    continue
                path = os.path.join(dirpath, fn)
                rel = os.path.relpath(path, ROOT)
                lines = open(path, errors='replace').read().split('\n')
                for line_no, text in comment_blocks(lines):
                    if MARKER.search(text):
                        kind = next(k for k, r in KIND if r.search(text))
                        entries.append((rel, line_no, kind, text))
    return entries


def render(entries):
    out = [
        '# Deviations and unported pieces',
        '',
        'Generated by `tools/triage/deviations.py` from comments in the Rust sources; edit the',
        'comments, not this file. Each entry is a known place where the port differs from the',
        'original or stops short of it.',
        '',
    ]
    counts = {}
    for _, _, kind, _ in entries:
        counts[kind] = counts.get(kind, 0) + 1
    out.append(', '.join(f'{k}: {v}' for k, v in sorted(counts.items())) + '.')
    current = None
    for rel, line_no, kind, text in sorted(entries):
        if rel != current:
            out += ['', f'## `{rel}`', '']
            current = rel
        out.append(f'- [{kind}] [{rel}:{line_no}]({os.path.relpath(os.path.join(ROOT, rel), os.path.dirname(OUT))}#L{line_no}): {text}')
    return '\n'.join(out) + '\n'


def main():
    text = render(collect())
    if '--check' in sys.argv:
        old = open(OUT).read() if os.path.exists(OUT) else ''
        if old != text:
            print('docs/DEVIATIONS.md is stale; run tools/triage/deviations.py')
            return 1
        return 0
    with open(OUT, 'w') as f:
        f.write(text)
    print(f'wrote {OUT} ({text.count(chr(10) + "- [")} entries)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
