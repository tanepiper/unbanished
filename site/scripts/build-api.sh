#!/usr/bin/env bash
# Build the Rust API documentation of the libraries into site/public/api/, for the website.
#
#   site/scripts/build-api.sh
#
# Runs `cargo doc` for the library crates only (not their dependencies), in its own target
# folder (target/api). On Linux, it needs the ALSA headers (libasound2-dev), as a normal build
# does. The site links to the result at /api/; VitePress copies site/public/ into the site.
set -euo pipefail

site="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$site/.." && pwd)"
crates=(banished-core banished-terrain banished-path banished-game banished-formats banished-ui
  banished-gfx banished-audio banished-wma)

args=()
for c in "${crates[@]}"; do args+=(-p "$c"); done
export CARGO_TARGET_DIR="$repo/target/api"
# The dark theme by default, with the website's colours (api-header.html).
export RUSTDOCFLAGS="--default-theme=dark --html-in-header $site/scripts/api-header.html"
cargo doc --manifest-path "$repo/Cargo.toml" --no-deps --lib "${args[@]}"

out="$site/public/api"
rm -rf "$out"
cp -R "$CARGO_TARGET_DIR/doc" "$out"

# rustdoc writes no page for the folder itself; add one that lists the crates.
describe() {
  case "$1" in
    banished-core) echo "Exact maths, the game's random numbers, Perlin noise, game time and the calendar." ;;
    banished-terrain) echo "Map generation from a seed, the terrain mesh, rivers, ground height and cell types." ;;
    banished-path) echo "The A* pathfinder, walkable regions and the sector graph." ;;
    banished-game) echo "The game rules: citizens, jobs, buildings, farming, trade, nature and disasters." ;;
    banished-formats) echo "Readers for the game's packages, resources and save files." ;;
    banished-ui) echo "The game's interface system: elements, layout, text, controls and input." ;;
    banished-gfx) echo "Rendering shared by the game and the viewer, with wgpu." ;;
    banished-audio) echo "Sound decoding and playback: the 64-channel device and the sound scene." ;;
    banished-wma) echo "A decoder for Windows Media Audio v2, the codec of the game's sounds." ;;
  esac
}
{
  cat <<'HTML'
<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Un-Banished API documentation</title>
<link rel="icon" href="https://tanepiper.github.io/unbanished/favicon.svg">
<style>
  :root { --bg: #14100c; --card: #1b1611; --line: #3a3026; --text: #ece4d3; --soft: #bdb39f; --gold: #e6bf6a; }
  @media (prefers-color-scheme: light) {
    :root { --bg: #faf6ee; --card: #fffdf8; --line: #e2d6c0; --text: #2a2118; --soft: #6b5d4b; --gold: #8a5a17; }
  }
  * { box-sizing: border-box; }
  body { margin: 0; background: var(--bg); color: var(--text);
         font: 16px/1.6 "Fira Sans", system-ui, -apple-system, "Segoe UI", sans-serif; }
  main { max-width: 820px; margin: 0 auto; padding: 48px 16px 64px; }
  header { display: flex; gap: 16px; align-items: center; margin-bottom: 8px; }
  header img { width: 56px; height: 56px; }
  h1 { font-size: 30px; margin: 0; }
  p { color: var(--soft); }
  a { color: var(--gold); }
  ul { list-style: none; padding: 0; display: grid; gap: 12px; margin: 28px 0; }
  li a { display: block; padding: 14px 18px; background: var(--card); border: 1px solid var(--line);
         border-radius: 10px; text-decoration: none; }
  li a:hover { border-color: var(--gold); }
  li code { font: 600 17px/1.4 "Fira Mono", ui-monospace, monospace; color: var(--gold); }
  li span { display: block; color: var(--soft); font-size: 15px; margin-top: 2px; }
</style>
</head>
<body>
<main>
<header>
  <img src="https://tanepiper.github.io/unbanished/assets/un-banished-icon.svg" alt="">
  <h1>Un-Banished API documentation</h1>
</header>
<p>The Rust API documentation of the libraries of Un-Banished, generated by <code>cargo doc</code> from the
source code. Each crate's first page is its README, with examples. Every ported item names the
original function it came from in its last line, <em>Original</em>.</p>
<p><a href="../develop/api">About this documentation</a> · <a href="../reference/">Apps and crates</a> ·
<a href="../">The website</a></p>
<ul>
HTML
  for c in "${crates[@]}"; do
    dir="${c//-/_}"
    echo "  <li><a href=\"$dir/index.html\"><code>$c</code><span>$(describe "$c")</span></a></li>"
  done
  cat <<'HTML'
</ul>
</main>
</body>
</html>
HTML
} >"$out/index.html"
echo "api: $out (served at /api/)"
