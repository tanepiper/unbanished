// Builds the site's generated pages from the repository's own documents, so the site and the
// repository say the same thing. Run before `vitepress build` and `vitepress dev`.
//
// Generated (git-ignored): guide/index.md, about/how-it-was-made.md, about/status.md,
// about/faq.md, about/licence.md, contribute.md, and public/assets/, public/favicon.svg.
// Hand-written: index.md, play.md, about/index.md.
import { cpSync, mkdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { dirname, join, normalize, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const site = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repo = resolve(site, '..')
const GITHUB = 'https://github.com/tanepiper/unbanished'

// Repository files that have a page on the site.
const PAGES = {
  'README.md': '/',
  'docs/USER-GUIDE.md': '/guide/',
  'docs/PROCESS.md': '/about/how-it-was-made',
}

/** Rewrite one link target found in `from` (a repository-relative file). */
function target(href, from) {
  if (/^(https?:|mailto:|#)/.test(href)) return href
  const [path, anchor] = href.split('#')
  const file = normalize(join(dirname(from), path)).replace(/\\/g, '/')
  const hash = anchor ? `#${anchor}` : ''
  if (PAGES[file]) return PAGES[file] + (file === 'README.md' ? '' : hash)
  if (file.startsWith('docs/assets/')) return '/' + file.slice('docs/'.length)
  const kind = existsSync(join(repo, file)) && statSync(join(repo, file)).isDirectory() ? 'tree' : 'blob'
  return `${GITHUB}/${kind}/main/${file}${hash}`
}

/** Rewrite markdown links and images, and HTML src/href attributes. */
function rewrite(md, from) {
  return md
    .replace(/(\]\()([^)\s]+)(\))/g, (_, a, href, b) => a + target(href, from) + b)
    .replace(/\b(src|href)="([^"]+)"/g, (_, attr, href) => `${attr}="${target(href, from)}"`)
}

/** The body of a `## heading` section of a markdown file. */
function section(md, heading) {
  const start = md.indexOf(`\n## ${heading}\n`)
  if (start < 0) throw new Error(`section not found: ${heading}`)
  const body = md.slice(start + heading.length + 5)
  const end = body.search(/\n## /)
  return (end < 0 ? body : body.slice(0, end)).trim()
}

/** Drop the centred logo paragraph that opens the repository's documents. */
function dropLogo(md) {
  return md.replace(/^<p align="center"><img src="[^"]*un-banished-logo\.svg"[^>]*><\/p>\s*/, '')
}

function page(file, frontmatter, body) {
  const fm = Object.entries(frontmatter)
    .map(([k, v]) => `${k}: ${JSON.stringify(v)}`)
    .join('\n')
  const out = join(site, file)
  mkdirSync(dirname(out), { recursive: true })
  const note = `<!-- Generated by site/scripts/prepare.mjs. Edit the source in the repository instead. -->`
  writeFileSync(out, `---\n${fm}\n---\n\n${note}\n\n${body.trim()}\n`)
}

const read = (f) => readFileSync(join(repo, f), 'utf8')
const readme = read('README.md')

page(
  'guide/index.md',
  { title: 'Setup guide', description: 'Install Un-Banished and start playing.', outline: [2, 3] },
  rewrite(dropLogo(read('docs/USER-GUIDE.md')), 'docs/USER-GUIDE.md'),
)
page(
  'about/how-it-was-made.md',
  { title: 'How it was made', description: 'How Ghidra, REA, an AI agent and a human rebuilt Banished.', outline: [2, 3] },
  rewrite(dropLogo(read('docs/PROCESS.md')), 'docs/PROCESS.md'),
)
page(
  'about/status.md',
  { title: 'Status', description: 'What works today, and what is still open.' },
  `# Status\n\n${rewrite(section(readme, 'Status'), 'README.md')}`,
)
page(
  'about/faq.md',
  { title: 'Questions and answers', description: 'Common questions about Un-Banished.' },
  `# Questions and answers\n\n${rewrite(section(readme, 'FAQ'), 'README.md')}`,
)
page(
  'about/licence.md',
  { title: 'Licence and legal', description: 'The licence of Un-Banished, and its relation to Banished.' },
  `# Licence and legal\n\n## Licence\n\n${rewrite(section(readme, 'Licence'), 'README.md')}\n\n` +
    `## Legal\n\n${rewrite(section(readme, 'Legal'), 'README.md')}`,
)
page(
  'contribute.md',
  { title: 'Contribute', description: 'How the code is organised, and how to help.' },
  `# Contribute\n\n${rewrite(section(readme, 'For developers'), 'README.md')}\n\n` +
    `## Report a problem\n\nIf something works differently from the original game, or does not work, ` +
    `please [open an issue](${GITHUB}/issues/new/choose). The forms ask for the information we need.`,
)

// Images: the logo, icons, diagram and screenshots, from docs/assets.
const assets = join(site, 'public', 'assets')
mkdirSync(assets, { recursive: true })
cpSync(join(repo, 'docs', 'assets'), assets, { recursive: true })
cpSync(join(repo, 'docs', 'assets', 'un-banished-icon-small.svg'), join(site, 'public', 'favicon.svg'))

const generated = ['guide/index.md', 'about/how-it-was-made.md', 'about/status.md', 'about/faq.md', 'about/licence.md', 'contribute.md']
console.log(`prepare: wrote ${generated.length} pages and copied docs/assets (${relative(repo, assets)})`)
if (!existsSync(join(site, 'public', 'game', 'index.html'))) {
  console.log('prepare: no game build in public/game; run scripts/build-game.sh to include it')
}
